// Build the GIF worker (gifenc + our encoder) into src/export/gif-source.generated.ts as one string, which
// "Save as video" starts as a Blob worker. Runs before build, typecheck and tests (the file is git-ignored).
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const r = await build({ entryPoints: ['src/export/gif.worker.ts'], bundle: true, minify: true, format: 'iife', target: 'es2021', write: false, legalComments: 'none',
  banner: { js: '/*! gifenc (MIT License) Copyright (c) 2017 Matt DesLauriers */' } });
const code = r.outputFiles[0].text;
writeFileSync('src/export/gif-source.generated.ts', `// Generated by scripts/gif-worker.mjs from src/export/gif.worker.ts (gifenc is MIT, © Matt DesLauriers). Do not edit.\nexport default ${JSON.stringify(code)};\n`);
console.log(`gif worker: ${(code.length / 1024).toFixed(1)} KB`);
